-- ============================================================

-- updated_at for messages
CREATE OR REPLACE FUNCTION message_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS message_updated_at ON messages;
CREATE TRIGGER message_updated_at
  BEFORE UPDATE ON messages
  FOR EACH ROW EXECUTE FUNCTION message_set_updated_at();

-- Guard: prevent changes to sender_id, conversation_id, created_at
CREATE OR REPLACE FUNCTION guard_message_immutable()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.sender_id <> OLD.sender_id THEN
    RAISE EXCEPTION 'Cannot change message sender_id';
  END IF;
  IF NEW.conversation_id <> OLD.conversation_id THEN
    RAISE EXCEPTION 'Cannot change message conversation_id';
  END IF;
  IF NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'Cannot change message created_at';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS message_guard_immutable ON messages;
CREATE TRIGGER message_guard_immutable
  BEFORE UPDATE ON messages
  FOR EACH ROW EXECUTE FUNCTION guard_message_immutable();

REVOKE EXECUTE ON FUNCTION guard_message_immutable() FROM PUBLIC, anon, authenticated;

-- Update conversation last_message_at when a message is inserted
CREATE OR REPLACE FUNCTION update_conversation_on_message()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE conversations
  SET last_message_at = NEW.created_at,
      updated_at = now()
  WHERE id = NEW.conversation_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS msg_update_conversation ON messages;
CREATE TRIGGER msg_update_conversation
  AFTER INSERT ON messages
  FOR EACH ROW EXECUTE FUNCTION update_conversation_on_message();

REVOKE EXECUTE ON FUNCTION update_conversation_on_message() FROM PUBLIC, anon, authenticated;

-- Notify the OTHER participant when a new message is sent
CREATE OR REPLACE FUNCTION notify_new_message()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  conv_traveler_id uuid;
  conv_sender_id uuid;
  recipient_id uuid;
BEGIN
  SELECT traveler_id, sender_id INTO conv_traveler_id, conv_sender_id
  FROM conversations WHERE id = NEW.conversation_id;

  -- Determine the recipient (the other participant)
  IF NEW.sender_id = conv_traveler_id THEN
    recipient_id := conv_sender_id;
  ELSIF NEW.sender_id = conv_sender_id THEN
    recipient_id := conv_traveler_id;
  ELSE
    RETURN NEW; -- sender is not a participant, shouldn't happen but safety
  END IF;

  INSERT INTO notifications (user_id, type, title, body, related_conversation_id, related_message_id)
  VALUES (
    recipient_id,
    'new_message',
    'New message',
    'You have received a new message.',
    NEW.conversation_id,
    NEW.id
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS msg_notify_recipient ON messages;
CREATE TRIGGER msg_notify_recipient
  AFTER INSERT ON messages
  FOR EACH ROW EXECUTE FUNCTION notify_new_message();

REVOKE EXECUTE ON FUNCTION notify_new_message() FROM PUBLIC, anon, authenticated;

-- ============================================================
-- 8. RLS — CONVERSATIONS
-- ============================================================

ALTER TABLE conversations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "conv_select" ON conversations;
CREATE POLICY "conv_select"
ON conversations FOR SELECT
TO authenticated
USING (
  auth.uid() = traveler_id
  OR auth.uid() = sender_id
  OR public.is_admin()
);

-- No INSERT policy for authenticated — conversations are created only by trigger
DROP POLICY IF EXISTS "conv_insert" ON conversations;
CREATE POLICY "conv_insert"
ON conversations FOR INSERT
TO authenticated
WITH CHECK (false);

DROP POLICY IF EXISTS "conv_update" ON conversations;
CREATE POLICY "conv_update"
ON conversations FOR UPDATE
TO authenticated
USING (
  auth.uid() = traveler_id
  OR auth.uid() = sender_id
  OR public.is_admin()
)
WITH CHECK (
  auth.uid() = traveler_id
  OR auth.uid() = sender_id
  OR public.is_admin()
);

DROP POLICY IF EXISTS "conv_delete" ON conversations;
CREATE POLICY "conv_delete"
ON conversations FOR DELETE
TO authenticated
USING (public.is_admin());

GRANT SELECT, UPDATE, DELETE ON conversations TO authenticated;

-- ============================================================
-- 9. RLS — MESSAGES
-- ============================================================

ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "msg_select" ON messages;
CREATE POLICY "msg_select"
ON messages FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM conversations c
    WHERE c.id = messages.conversation_id
    AND (c.traveler_id = auth.uid() OR c.sender_id = auth.uid())
  )
  OR public.is_admin()
);

DROP POLICY IF EXISTS "msg_insert" ON messages;
CREATE POLICY "msg_insert"
ON messages FOR INSERT
TO authenticated
WITH CHECK (
  auth.uid() = sender_id
  AND EXISTS (
    SELECT 1 FROM conversations c
    WHERE c.id = messages.conversation_id
    AND (c.traveler_id = auth.uid() OR c.sender_id = auth.uid())
  )
);

DROP POLICY IF EXISTS "msg_update" ON messages;
CREATE POLICY "msg_update"
ON messages FOR UPDATE
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM conversations c
    WHERE c.id = messages.conversation_id
    AND (c.traveler_id = auth.uid() OR c.sender_id = auth.uid())
  )
  OR public.is_admin()
)
WITH CHECK (
  EXISTS (
    SELECT 1 FROM conversations c
    WHERE c.id = messages.conversation_id
    AND (c.traveler_id = auth.uid() OR c.sender_id = auth.uid())
  )
  OR public.is_admin()
);

DROP POLICY IF EXISTS "msg_delete" ON messages;
CREATE POLICY "msg_delete"
ON messages FOR DELETE
TO authenticated
USING (public.is_admin());

GRANT SELECT, INSERT, UPDATE, DELETE ON messages TO authenticated;

